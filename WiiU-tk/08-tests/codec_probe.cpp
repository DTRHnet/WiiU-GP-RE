// codec_probe — measures what the GamePad's H.264 path actually produces.
//
// Hardware-free. Answers three questions that decide whether a stream will work:
//
//   presets <frames>
//     Encode identical content with libdrc's exact DRH parameters at several
//     x264 presets and report bytes/frame, per-chunk sizes, and how many chunks
//     exceed the vstrm payload ceiling. libdrc ships preset "slow"; the
//     open question is what that costs on a 1400 B / 1694 B packet budget.
//
//   idr
//     Reproduces wozt/libdrc's finding on THIS drc-x264 build: with intra
//     refresh enabled, does asking for idr=true actually emit NAL_SLICE_IDR?
//     If not, every "recover the decoder" path in the stack is a no-op.
//
//   keyint
//     Same, but with intra refresh off and a forced keyint, to show that a real
//     IDR is only obtainable that way (or by restarting the encoder).
//
// Build/run is done by tests/run-codec-probe.sh.
#include <cstdio>
#include <cstring>
#include <cstdlib>
#include <vector>

#include <cstdint>
extern "C" {
#include <x264.h>
}

#include <drc/screen.h>

static const int kW = drc::kScreenWidth;   // 864 in libdrc's headers
static const int kH = drc::kScreenHeight;  // 480
static const size_t kMaxVstrmPayload = 1694;  // libdrc kMaxVstrmPayloadSize
static const size_t kPacedPayload    = 1400;  // payload libdrc actually paces at

static void fill_i420(std::vector<drc::byte>& f, int frame) {
  drc::byte* y = f.data();
  drc::byte* u = y + kW * kH;
  drc::byte* v = u + (kW * kH) / 4;
  for (int j = 0; j < kH; ++j)
    for (int i = 0; i < kW; ++i)
      y[j * kW + i] = (drc::byte)((i + j + frame * 7) & 0xFF);
  for (int j = 0; j < kH / 2; ++j)
    for (int i = 0; i < kW / 2; ++i) {
      u[j * (kW / 2) + i] = (drc::byte)(64 + ((i + frame) & 0x7F));
      v[j * (kW / 2) + i] = (drc::byte)(192 - ((j + frame) & 0x7F));
    }
  // Optional pseudo-random texture: approximates real photographic content,
  // which is what actually breaks the 1400 B packet budget.
  if (getenv("DRC_PROBE_NOISE")) {
    unsigned s = 12345u + (unsigned)frame * 7919u;
    for (size_t k = 0; k < (size_t)kW * kH; ++k) {
      s = s * 1103515245u + 12345u;
      int n = (int)((s >> 16) & 0x3F) - 32;
      int v = (int)y[k] + n;
      y[k] = (drc::byte)(v < 0 ? 0 : (v > 255 ? 255 : v));
    }
  }
}

// libdrc's parameter set (src/h264-encoder.cpp), with the preset selectable and
// the intra-refresh/keyint policy selectable.
static void base_params(x264_param_t& p, const char* preset, int drh) {
  x264_param_default_preset(&p, preset, "zerolatency");
  p.i_width = kW;
  p.i_height = kH;
  p.analyse.inter &= ~X264_ANALYSE_PSUB16x16;
  p.i_scenecut_threshold = -1;
  p.i_csp = X264_CSP_I420;
  p.b_cabac = 1;
  p.b_interlaced = 0;
  p.i_bframe = 0;
  p.i_bframe_pyramid = 0;
  p.i_frame_reference = 1;
  p.b_constrained_intra = 1;
  p.analyse.i_weighted_pred = 0;
  p.analyse.b_weighted_bipred = 0;
  p.analyse.b_transform_8x8 = 0;
  p.analyse.i_chroma_qp_offset = 0;
  p.rc.i_rc_method = X264_RC_CQP;
  p.rc.i_qp_constant = p.rc.i_qp_min = p.rc.i_qp_max = 32;
  p.rc.f_ip_factor = 1.0;
  p.b_aud = 0;
  p.b_drh_mode = drh;
  p.i_threads = 1;
  p.b_sliced_threads = 0;
  p.i_slice_count = 1;
  p.i_log_level = X264_LOG_NONE;
  x264_param_apply_profile(&p, "main");
}

struct ChunkStat { size_t total = 0; size_t max_chunk = 0; int over_paced = 0;
                   int over_max = 0; int chunks = 0; };

static x264_t* g_enc = nullptr;
static ChunkStat g_stat;

static void chunk_cb(x264_t*, x264_nal_t* nal, void*) {
  if (nal->i_type == NAL_SEI) return;
  const size_t len = (size_t)nal->i_payload;
  g_stat.total += len;
  ++g_stat.chunks;
  if (len > g_stat.max_chunk) g_stat.max_chunk = len;
  if (len > kPacedPayload) ++g_stat.over_paced;
  if (len > kMaxVstrmPayload) ++g_stat.over_max;
}

// Optional source: a raw I420 file (real content captured or generated by
// ffmpeg), replayed frame by frame instead of synthetic gradients.
static FILE* g_yuv = nullptr;
static size_t g_yuv_frames = 0;
static size_t g_yuv_pos = 0;

static void load_frame(std::vector<drc::byte>& f, int frame) {
  const size_t need = (size_t)kW * kH * 3 / 2;
  if (g_yuv) {
    size_t idx = (size_t)frame % (g_yuv_frames ? g_yuv_frames : 1);
    if (fseek(g_yuv, (long)(idx * need), SEEK_SET) == 0 &&
        fread(f.data(), 1, need, g_yuv) == need)
      return;
  }
  fill_i420(f, frame);
}

static int mode_presets(int frames) {
  const char* presets[] = {"slow", "medium", "fast", "ultrafast"};
  std::vector<drc::byte> frame((size_t)kW * kH * 3 / 2);

  printf("%-10s %10s %10s %10s %8s %8s %8s\n", "preset", "B/frame", "avg chunk",
         "max chunk", ">1400", ">1694", "kbps@60");
  for (const char* preset : presets) {
    x264_param_t p;
    base_params(p, preset, /*drh=*/1);
    p.b_repeat_headers = 0;
    p.nalu_process = chunk_cb;
    x264_t* e = x264_encoder_open(&p);
    if (!e) { printf("%-10s encoder open failed\n", preset); continue; }

    size_t grand_total = 0; size_t grand_max = 0;
    int grand_paced = 0, grand_over = 0, grand_chunks = 0;
    for (int n = 0; n < frames; ++n) {
      load_frame(frame, n);
      x264_picture_t in, outp;
      x264_picture_init(&in);
      in.img.i_csp = X264_CSP_I420;
      in.img.i_plane = 3;
      in.img.i_stride[0] = kW;
      in.img.i_stride[1] = kW / 2;
      in.img.i_stride[2] = kW / 2;
      in.img.plane[0] = frame.data();
      in.img.plane[1] = frame.data() + (size_t)kW * kH;
      in.img.plane[2] = in.img.plane[1] + (size_t)(kW * kH) / 4;
      // DRC_PROBE_ALLIDR simulates a GamePad that requests a keyframe on every
      // frame (the failure mode reported with x264 preset "slow" on real video):
      // it shows what that costs on the link.
      in.i_type = (n == 0 || getenv("DRC_PROBE_ALLIDR")) ? X264_TYPE_IDR : X264_TYPE_P;
      x264_nal_t* nals = nullptr; int nc = 0;
      g_stat = ChunkStat();
      if (x264_encoder_encode(e, &nals, &nc, &in, &outp) < 0) break;
      grand_total += g_stat.total;
      if (g_stat.max_chunk > grand_max) grand_max = g_stat.max_chunk;
      if (getenv("DRC_PROBE_VERBOSE") && n < 8)
        printf("    %-9s frame %2d: %6zu B  max chunk %5zu B  chunks %d  split>1400 %d\n",
               preset, n, g_stat.total, g_stat.max_chunk, g_stat.chunks, g_stat.over_paced);
      grand_paced += g_stat.over_paced;
      grand_over += g_stat.over_max;
      grand_chunks += g_stat.chunks;
    }
    x264_encoder_close(e);
    printf("%-10s %10zu %10zu %10zu %8d %8d %8.0f\n", preset,
           grand_total / (size_t)frames, grand_total / (size_t)(grand_chunks ? grand_chunks : 1),
           grand_max, grand_paced, grand_over,
           (double)grand_total * 8.0 * 60.0 / 1000.0 / (double)frames);
  }
  printf("\nPacket budget: %zu B paced, %zu B hard max (kMaxVstrmPayloadSize)\n",
         kPacedPayload, kMaxVstrmPayload);
  printf("Measured: %d chunks/frame expected (30 MB rows / 6 per chunk)\n", 5);
  return 0;
}

// Count NAL types emitted when we ask for an IDR mid-stream.
static int nal_counts[32];

static void type_cb(x264_t*, x264_nal_t* nal, void*) {
  if (nal->i_type >= 0 && nal->i_type < 32) ++nal_counts[nal->i_type];
}

static int mode_idr(int intra_refresh, int keyint) {
  std::vector<drc::byte> frame((size_t)kW * kH * 3 / 2);
  x264_param_t p;
  const char* preset = getenv("DRC_PROBE_PRESET");
  base_params(p, preset ? preset : "medium", /*drh=*/1);
  p.b_repeat_headers = 0;
  p.nalu_process = type_cb;
  p.b_intra_refresh = intra_refresh;
  if (keyint > 0) p.i_keyint_min = p.i_keyint_max = keyint;
  else { p.i_keyint_min = 10; p.i_keyint_max = 30; }

  x264_t* e = x264_encoder_open(&p);
  if (!e) { printf("encoder open failed\n"); return 1; }
  memset(nal_counts, 0, sizeof(nal_counts));

  const int kFrames = 60;
  int idr_after_requests = 0;
  for (int n = 0; n < kFrames; ++n) {
    fill_i420(frame, n);
    x264_picture_t in, outp;
    x264_picture_init(&in);
    in.img.i_csp = X264_CSP_I420;
    in.img.i_plane = 3;
    in.img.i_stride[0] = kW;
    in.img.i_stride[1] = kW / 2;
    in.img.i_stride[2] = kW / 2;
    in.img.plane[0] = frame.data();
    in.img.plane[1] = frame.data() + (size_t)kW * kH;
    in.img.plane[2] = in.img.plane[1] + (size_t)(kW * kH) / 4;
    // Frame 0 is the stream start; frames 10/20/30/40 simulate the GamePad's
    // "please send a keyframe" resync request.
    if (n == 0) in.i_type = X264_TYPE_IDR;
    else if (n >= 10 && n % 10 == 0) { in.i_type = X264_TYPE_IDR; ++idr_after_requests; }
    else in.i_type = X264_TYPE_P;

    const int before = nal_counts[NAL_SLICE_IDR];
    x264_nal_t* nals = nullptr; int nc = 0;
    if (x264_encoder_encode(e, &nals, &nc, &in, &outp) < 0) break;
    (void)before;
  }
  x264_encoder_close(e);

  printf("preset=%s intra_refresh=%d keyint=%d\n", getenv("DRC_PROBE_PRESET") ? getenv("DRC_PROBE_PRESET") : "medium", intra_refresh, keyint);
  printf("  requests for IDR mid-stream: %d\n", idr_after_requests);
  printf("  NAL_SLICE_IDR emitted:       %d\n", nal_counts[NAL_SLICE_IDR]);
  printf("  NAL_SLICE emitted:           %d\n", nal_counts[NAL_SLICE]);
  printf("  SPS/PPS emitted:             %d/%d\n", nal_counts[NAL_SPS], nal_counts[NAL_PPS]);
  if (idr_after_requests > 0 && nal_counts[NAL_SLICE_IDR] <= 1)
    printf("  => VERDICT: idr=true is a NO-OP; the decoder can never recover\n");
  else if (nal_counts[NAL_SLICE_IDR] > 1)
    printf("  => VERDICT: real IDRs are emitted\n");
  else
    printf("  => VERDICT: only the initial IDR; no recovery possible\n");
  return 0;
}

int main(int argc, char** argv) {
  if (argc < 2) {
    printf("usage: %s presets [frames] | idr\n", argv[0]);
    return 2;
  }
  if (!strcmp(argv[1], "presets")) return mode_presets(argc > 2 ? atoi(argv[2]) : 30);
  if (!strcmp(argv[1], "yuv") && argc > 2) {
    const size_t need = (size_t)kW * kH * 3 / 2;
    g_yuv = fopen(argv[2], "rb");
    if (!g_yuv) { printf("cannot open %s\n", argv[2]); return 1; }
    fseek(g_yuv, 0, SEEK_END);
    g_yuv_frames = (size_t)ftell(g_yuv) / need;
    printf("source: %s  %zu frames at %dx%d\n", argv[2], g_yuv_frames, kW, kH);
    return mode_presets(argc > 3 ? atoi(argv[3]) : (int)(g_yuv_frames ? g_yuv_frames : 30));
  }
  if (!strcmp(argv[1], "idr")) {
    printf("--- A: libdrc default policy (intra refresh on) ---\n");
    mode_idr(/*intra_refresh=*/1, 0);
    printf("\n--- B: forced keyint, intra refresh off ---\n");
    mode_idr(/*intra_refresh=*/0, 30);
    return 0;
  }
  printf("unknown mode\n");
  return 2;
}
