#!/usr/bin/env bash
# prepublish-audit.sh — fail-closed check that this repo contains only original work.
#
# Run from the repository root BEFORE every push:
#     bash WiiU-tk/_meta/prepublish-audit.sh
#     bash WiiU-tk/_meta/prepublish-audit.sh --staged   # only what is staged
#
# Exit 0 = safe to push. Exit 1 = something must be fixed first.
#
# Design note: this script contains NO secrets itself, so it is safe to publish.
# The real console identifiers live in _meta/.private-deny-patterns, which is
# git-ignored. If that file is missing the audit warns instead of silently
# passing, so a fresh clone knows it is running a reduced check.
set -uo pipefail

cd "$(dirname "$0")/../.." || exit 2
ROOT=$(pwd)

FAIL=0
WARN=0
fail() { printf '  \033[31mFAIL\033[0m %s\n' "$*"; FAIL=$((FAIL+1)); }
warn() { printf '  \033[33mWARN\033[0m %s\n' "$*"; WARN=$((WARN+1)); }
ok()   { printf '  \033[32m ok \033[0m %s\n' "$*"; }

# ---------------------------------------------------------------- file list
if [ "${1:-}" = "--staged" ]; then
  mapfile -t FILES < <(git diff --cached --name-only --diff-filter=ACMR 2>/dev/null)
  SCOPE="staged files"
else
  if git rev-parse --git-dir >/dev/null 2>&1; then
    mapfile -t FILES < <(git ls-files 2>/dev/null)
    SCOPE="tracked files"
  else
    mapfile -t FILES < <(find WiiU-tk -type f 2>/dev/null)
    SCOPE="worktree files (no git repo yet)"
  fi
fi

echo "prepublish-audit: checking ${#FILES[@]} $SCOPE"
[ "${#FILES[@]}" -eq 0 ] && { echo "  (nothing to audit)"; exit 0; }

# Everything in the audit is scoped to the publish allowlist.
ALLOWED_PREFIX_RE='^(\.gitignore|\.gitattributes|README\.md|LICENSE|THIRD-PARTY\.md|WiiU-tk/)'
# Anchored to the repository root: the vendored trees only ever live at top level.
# Anchoring matters — an unanchored 'research/' would also reject our own
# WiiU-tk/00-docs/research/ findings directory.
DENIED_PATH_RE='^(pc2drc|build|kernel|out|capture|research|run|tests)/|(^|/)\.git/'
THIRD_PARTY_COPY_RE='^(libdrc|drc-hostap|drc-x264|libdrc-vnc|drcvncclient|hostap-[0-9]|wozt-libdrc|barista)/'

echo
echo "[1] only allowlisted paths are present"
for f in "${FILES[@]}"; do
  if ! [[ "$f" =~ $ALLOWED_PREFIX_RE ]]; then
    fail "outside allowlist: $f"
  elif [[ "$f" =~ $DENIED_PATH_RE ]]; then
    fail "vendored/denied path: $f"
  elif [[ "$f" =~ $THIRD_PARTY_COPY_RE ]]; then
    fail "looks like a third-party tree: $f"
  fi
done
[ "$FAIL" -eq 0 ] && ok "all paths inside the allowlist"

echo
echo "[2] no vendored third-party source or binary blobs"
BLOBS=0
for f in "${FILES[@]}"; do
  [ -f "$f" ] || continue
  if file -b --mime "$f" 2>/dev/null | grep -qE '^application/(x-|octet-stream)'; then
    case "$f" in
      *.bin) warn "small binary table (review once): $f" ;;
      *)     fail "binary blob tracked: $f ($(file -b "$f" 2>/dev/null | cut -c1-40))"; BLOBS=$((BLOBS+1)) ;;
    esac
  fi
done
[ "$BLOBS" -eq 0 ] && ok "no unexpected binary content"

echo
echo "[3] patch files contain no binary hunks or build artefacts"
PATCH_BAD=0
for f in "${FILES[@]}"; do
  case "$f" in *.patch|*.diff) ;; *) continue ;; esac
  [ -f "$f" ] || continue
  if grep -qE '^GIT binary patch' "$f"; then
    fail "$f embeds a 'GIT binary patch' (compiled third-party code)"; PATCH_BAD=$((PATCH_BAD+1))
  fi
  if grep -qE '^\+\+\+ b/.*(\.deps/[^/]*\.Po|/config\.h)$' "$f"; then
    warn "$f diffs autogenerated build artefacts (.Po / config.h)"
  fi
done
[ "$PATCH_BAD" -eq 0 ] && ok "no binary hunks in patch files"

echo
echo "[4] no live console secrets"
# Pattern file format: "<BLOCK|WARN>:<literal>".
#   BLOCK = credential material (WPA PSK, private key) — must never be published.
#   WARN  = device identifier (our own console/pad MAC) — printed on the hardware
#           and broadcast over the air, so publishing it is low risk, but a reader
#           can then fingerprint the device. Worth parameterising, not blocking.
DENY_FILE="WiiU-tk/_meta/.private-deny-patterns"
BLOCK_P=(); WARN_P=()
if [ -f "$DENY_FILE" ]; then
  mapfile -t BLOCK_P < <(grep -oP '(?<=^BLOCK:).*' "$DENY_FILE" 2>/dev/null)
  mapfile -t WARN_P  < <(grep -oP '(?<=^WARN:).*'  "$DENY_FILE" 2>/dev/null)
  ok "loaded ${#BLOCK_P[@]} BLOCK and ${#WARN_P[@]} WARN patterns"
else
  warn "$DENY_FILE missing — running without device-specific checks"
fi

SECRETS=0
for f in "${FILES[@]}"; do
  [ -f "$f" ] || continue
  # Credential and identifier scans use `grep -a` so that BINARY captures and
  # packet tables are scanned too. This matters: a real WPS credential-delivery
  # frame (uic-792-reply0.bin) contained the plaintext PSK as ASCII inside a
  # binary blob, and an earlier version of this script skipped *.bin and missed it.
  for p in "${BLOCK_P[@]:-}"; do
    [ -z "$p" ] && continue
    if grep -a -qF -- "$p" "$f" 2>/dev/null; then
      fail "credential material in $f: ${p:0:12}…"; SECRETS=$((SECRETS+1))
    fi
  done
  for p in "${WARN_P[@]:-}"; do
    [ -z "$p" ] && continue
    if grep -a -qF -- "$p" "$f" 2>/dev/null; then
      warn "device identifier in $f: ${p} (parameterise before publishing)"
    fi
  done
  # The remaining heuristics are text-only.
  case "$f" in *.pcap|*.bin|*.h264|*.so*|*.o|*.ko) continue ;; esac
  # generic shapes that should never appear in published text
  if grep -qE 'BEGIN ([A-Z]+ )?PRIVATE KEY' "$f" 2>/dev/null; then
    fail "private key material in $f"; SECRETS=$((SECRETS+1))
  fi
  # a 64-hex run looks like a WPA2 PSK, but checksum manifests are full of them.
  # Skip files whose purpose is hashing; elsewhere it is only a warning, because
  # the real PSK is already a hard BLOCK pattern above and that is what must block.
  case "$f" in
    *.tsv|*.sha256|*.sha256sum|*checksums*|*.log) continue ;;
  esac
  while IFS= read -r hx; do
    case "$hx" in
      00112233445566778899aabbccddeeff00112233445566778899aabbccddeeff) : ;; # documented lab default
      *) warn "64-hex PSK-shaped value in $f: ${hx:0:8}… (checksum or credential?)" ;;
    esac
  done < <(grep -oE '\b[0-9a-f]{64}\b' "$f" 2>/dev/null | sort -u)
done
[ "$SECRETS" -eq 0 ] && ok "no secrets detected"

echo
echo "[5] size limits (GitHub rejects >100 MB, warns >50 MB)"
for f in "${FILES[@]}"; do
  [ -f "$f" ] || continue
  sz=$(stat -c%s "$f" 2>/dev/null || echo 0)
  if [ "$sz" -gt 104857600 ]; then fail "over GitHub hard limit: $f ($((sz/1048576)) MB)"
  elif [ "$sz" -gt 52428800 ]; then warn "over 50 MB: $f ($((sz/1048576)) MB)"
  elif [ "$sz" -gt 1048576 ]; then warn "large file: $f ($((sz/1024)) KB)"
  fi
done
ok "size check complete"

echo
echo "[6] provenance notice present"
for f in THIRD-PARTY.md WiiU-tk/_meta/source-map.tsv; do
  [ -f "$f" ] && ok "$f" || warn "$f missing"
done

echo
if [ "$FAIL" -gt 0 ]; then
  printf '\033[31mRESULT: FAIL\033[0m — %d blocking issue(s), %d warning(s). Do not push.\n' "$FAIL" "$WARN"
  exit 1
fi
printf '\033[32mRESULT: PASS\033[0m — %d warning(s). Safe to push.\n' "$WARN"
